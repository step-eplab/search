def sigma_clip(y, lvl=3, n=1):
    med = np.nanmedian(y)
    std = np.nanstd(y)
    u = np.zeros(len(y), dtype=bool)
    for i in range(n):
        u |= abs(y - med) > lvl * std
    y[u] = np.nan
    return y
